import math 

user = input("Enter a number: ")

print("The square root of", user, "is", math.sqrt(float(user)))
print("The factorial of", user, "is", math.factorial(int(user)))
print("The sine of", user, "is", math.sin(float(user)))
print("The cosine of", user, "is", math.cos(float(user)))
print("The tangent of", user, "is", math.tan(float(user)))